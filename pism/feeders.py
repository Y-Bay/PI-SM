def get_network(name: str, v_min_pu: float = 0.95, v_max_pu: float = 1.05) -> pp.pandapowerNet:
    """Return the "33", "69" or "123" bus feeder with voltage limits set."""
    if name == "33":
        net = pn.case33bw()
    elif name == "69":
        net = _create_case69()
    elif name == "123":
        net = _create_case123()
    else:
        raise ValueError(f"unknown network {name!r}; use '33', '69' or '123'")
    net.bus["min_vm_pu"] = v_min_pu
    net.bus["max_vm_pu"] = v_max_pu
    return net


def get_slack_bus(net: pp.pandapowerNet) -> int:
    return int(net.ext_grid.bus.iloc[0])


def get_base_mva(net: pp.pandapowerNet) -> float:
    return net.sn_mva if hasattr(net, "sn_mva") else 1.0


def perturb_line_impedances(net: pp.pandapowerNet, delta: float,
                            rng: np.random.Generator) -> pp.pandapowerNet:
    """Copy of `net` with every line's r and x scaled by independent factors in [1-delta, 1+delta]."""
    net2 = copy.deepcopy(net)
    for idx, row in net2.line.iterrows():
        if not row.get("in_service", True):
            continue
        eps_r = rng.uniform(-delta, delta)
        eps_x = rng.uniform(-delta, delta)
        net2.line.at[idx, "r_ohm_per_km"] = row["r_ohm_per_km"] * (1 + eps_r)
        net2.line.at[idx, "x_ohm_per_km"] = row["x_ohm_per_km"] * (1 + eps_x)
    return net2


